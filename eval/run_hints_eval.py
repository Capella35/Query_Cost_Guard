#!/usr/bin/env python3
"""Semantic-hints rules on the pre-registered test set (eval/hints_test.yaml).

Scores the two rules' findings only: no warehouse, no model, free. Each
query is labeled join_key, fanout or none; a mistake is caught when the
rule of its kind fires, a correct query is a false alarm when anything
fires. Unqualified columns are resolved with the BigQuery registry's schema.

Run ONCE:  .venv/bin/python eval/run_hints_eval.py
Writes eval/RESULTS_hints_test.md and eval/results/hints_test_<ts>.json. A
later run needs --rerun and writes eval/RESULTS_hints_test_rerun.md.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from code_version import code_version, describe  # noqa: E402
from query_preflight import sql_ast  # noqa: E402
from query_preflight.semantic_hints import check, load_hints  # noqa: E402

KINDS = {"join key not declared": "join_key", "fan-out": "fanout"}


def kinds_of(findings: list[str]) -> set[str]:
    return {k for f in findings for prefix, k in KINDS.items() if f.startswith(prefix)}


def registry_has_column():
    """has_column(table, column) from the BigQuery registry file, if built."""
    import duckdb

    files = sorted((ROOT / "data" / "bigquery").glob("*.registry.duckdb"))
    if not files:
        return None
    con = duckdb.connect(str(files[0]), read_only=True)
    cols: dict[str, set] = {}
    for t, c in con.execute("SELECT table_name, column_name FROM column_registry").fetchall():
        cols.setdefault(t.lower(), set()).add(c.lower())
    con.close()
    return lambda t, c: c in cols.get(t, set())


def score(queries: list[dict], hints, has_column) -> tuple[list[dict], dict]:
    rows = []
    with sql_ast.using_dialect("bigquery"):
        for q in queries:
            try:
                findings, error = check(q["sql"], hints, has_column), None
            except Exception as e:  # noqa: BLE001 — a crash is a miss, recorded
                findings, error = [], f"{type(e).__name__}: {e}"
            got = kinds_of(findings)
            ok = (q["expect"] in got) if q["expect"] != "none" else not findings
            rows.append({"id": q["id"], "expect": q["expect"], "got": sorted(got), "ok": ok,
                         "findings": findings, "error": error, "question": q.get("question")})
    def frac(kind):
        sub = [r for r in rows if r["expect"] == kind]
        return f"{sum(r['ok'] for r in sub)}/{len(sub)}"
    metrics = {
        "join_key_caught": frac("join_key"),
        "fanout_caught": frac("fanout"),
        "false_alarms_on_correct": f"{sum(not r['ok'] for r in rows if r['expect'] == 'none')}"
                                   f"/{sum(r['expect'] == 'none' for r in rows)}",
        "exact": f"{sum(r['ok'] for r in rows)}/{len(rows)}",
        "errors": sum(r["error"] is not None for r in rows),
    }
    return rows, metrics


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rerun", action="store_true", help="after the first run: a tuning run")
    ap.add_argument("--set", default=str(ROOT / "eval" / "hints_test.yaml"))
    ap.add_argument("--hints", default=str(ROOT / "semantic_hints.yaml"))
    args = ap.parse_args(argv)
    first = ROOT / "eval" / "RESULTS_hints_test.md"
    if first.exists() and not args.rerun:
        raise SystemExit("the hints test set has been run (eval/RESULTS_hints_test.md); it is run "
                         "ONCE: pass --rerun for a labeled tuning run")
    version = code_version()  # before the run: what is measured
    import yaml

    queries = yaml.safe_load(Path(args.set).read_text())["queries"]
    rows, metrics = score(queries, load_hints(args.hints), registry_has_column())
    for k, v in metrics.items():
        print(f"{k}: {v}")
    ts = datetime.now(timezone.utc)
    out_dir = ROOT / "eval" / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"hints_test_{ts:%Y%m%d_%H%M%S}.json").write_text(json.dumps(
        {"ts": ts.isoformat(), "code_version": version, "metrics": metrics, "cases": rows}, indent=2))
    md = ["# Semantic-hints rules: TEST set (pre-registered)", ""]
    if args.rerun:
        md += ["**RERUN** — a tuning run: the first run (`RESULTS_hints_test.md`) stays the "
               "first measurement.", ""]
    md += [f"Generated by `eval/run_hints_eval.py` on {ts:%Y-%m-%d %H:%M} UTC, {describe(version)}. "
           f"{len(rows)} queries in `eval/hints_test.yaml`, labels fixed before the rules saw them. "
           "Rules' findings only (no warehouse, no model).", "",
           "| metric | value |", "|---|---|", *[f"| {k} | {v} |" for k, v in metrics.items()], "",
           "| id | expect | got | ok | question | finding |", "|---|---|---|---|---|---|"]
    for r in rows:
        f = (r["error"] or "; ".join(r["findings"]) or "—").replace("|", "/").replace("\n", " ")
        md.append(f"| {r['id']} | {r['expect']} | {', '.join(r['got']) or '—'} | "
                  f"{'yes' if r['ok'] else '**no**'} | {r['question']} | {f[:220]} |")
    name = "RESULTS_hints_test_rerun.md" if args.rerun else "RESULTS_hints_test.md"
    (ROOT / "eval" / name).write_text("\n".join(md) + "\n")
    print(f"summary -> eval/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
