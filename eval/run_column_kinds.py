#!/usr/bin/env python3
"""Column-kind eval (eval/column_kinds.yaml): today's name-pattern baseline vs
a Claude classification, on the 73 TheLook columns and the 20 hard columns.
Pre-registered; run ONCE (refuses a rerun without --rerun). One model call per
set; the model sees names, types and counts only.

Output: eval/RESULTS_column_kinds.md, eval/results/column_kinds_<ts>.json.

Run:  .venv/bin/python eval/run_column_kinds.py      (needs Anthropic credentials)
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from query_preflight.column_kinds import baseline_kind, score  # noqa: E402

RESULTS = ROOT / "eval" / "RESULTS_column_kinds.md"


def baseline(tables: dict) -> dict:
    return {(t, c["name"]): baseline_kind(c["name"], c["type"], spec["rows"], c["distinct"])
            for t, spec in tables.items() for c in spec["columns"]}


def adopted(base: dict, model: dict) -> bool:
    """The rule fixed in column_kinds.yaml, per set."""
    return not model["false_ids"] and len(model["missed_ids"]) <= len(base["missed_ids"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rerun", action="store_true")
    args = ap.parse_args()
    if RESULTS.exists() and not args.rerun:
        raise SystemExit("the column-kind eval has already been run (eval/RESULTS_column_kinds.md); "
                         "pass --rerun to run again — the summary will say it is a rerun")
    from query_preflight.llm import ClaudeLLM

    data = yaml.safe_load((ROOT / "eval" / "column_kinds.yaml").read_text())
    llm = ClaudeLLM()
    out = {"ts": datetime.now(timezone.utc).isoformat(), "model": llm.model, "sets": {}}
    for name in ("thelook", "hard"):
        tables = data[name]
        answer = llm.classify_columns(tables)
        model_pred = {k: v["kind"] for k, v in answer.items()}
        base, model = score(tables, baseline(tables)), score(tables, model_pred)
        out["sets"][name] = {
            "baseline": base, "model": model, "adopt_ok": adopted(base, model),
            "answers": {f"{t}.{c}": v for (t, c), v in answer.items()},
        }
        print(f"{name}: baseline {base['accuracy']} false_ids={base['false_ids']} "
              f"missed_ids={base['missed_ids']}")
        print(f"{name}: model    {model['accuracy']} false_ids={model['false_ids']} "
              f"missed_ids={model['missed_ids']}")
    out["model_calls"] = llm.calls
    dest = ROOT / "eval" / "results" / f"column_kinds_{datetime.now(timezone.utc):%Y%m%d_%H%M%S}.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(out, indent=2))
    adopt = all(s["adopt_ok"] for s in out["sets"].values())
    lines = ["# Column-kind eval: name pattern vs model", ""]
    if args.rerun:
        lines += ["**RERUN** — not the first, pre-registered measurement.", ""]
    lines += [f"Generated by `eval/run_column_kinds.py` on {out['ts'][:16]} UTC, model "
              f"`{out['model']}`, {out['model_calls']} calls. Labels, metrics and the adoption "
              "rule were committed before any model call (`eval/column_kinds.yaml`). The model "
              "saw names, types and counts only.", "",
              "| set | method | accuracy | false ids (would block a valid SUM) | missed ids |",
              "|---|---|---|---|---|"]
    for name, s in out["sets"].items():
        for m in ("baseline", "model"):
            r = s[m]
            lines.append(f"| {name} | {m} | {r['accuracy']} | {len(r['false_ids'])} "
                         f"{', '.join(r['false_ids'])} | {len(r['missed_ids'])} "
                         f"{', '.join(r['missed_ids'])} |")
    lines += ["", f"**Adoption rule** (false ids = 0 and missed ids <= baseline, on both sets): "
              f"**{'met' if adopt else 'NOT met'}**.", ""]
    for name, s in out["sets"].items():
        lines += [f"## Wrong kinds, {name}", ""]
        for m in ("baseline", "model"):
            lines.append(f"- **{m}**: " + ("; ".join(s[m]["wrong"]) or "none"))
        lines.append("")
    RESULTS.write_text("\n".join(lines))
    print(f"adoption rule {'met' if adopt else 'NOT met'}; results -> {dest.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
