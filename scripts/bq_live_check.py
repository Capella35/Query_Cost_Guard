#!/usr/bin/env python3
"""The Guard's `check` path live on BigQuery — dry runs, plus sampled rewrite checks.

Runs the 30-query TheLook set (a tuning set; the held-out set is not touched)
through guard.decide() twice: on the local DuckDB copy, and with
BigQueryWarehouse against the partitioned TheLook copies made by
scripts/bq_dryrun_compare.py --create-copies. Each query is adapted to
BigQuery SQL with to_bigquery() first (same adaptation as the dry-run
comparison).

This is NOT a scored eval: the labels were written for DuckDB's rows caps,
so the output compares verdicts across warehouses and reports what broke.
Both sides use the frozen eval caps (eval/eval_caps.yaml) so the policy is
the same.

Cost: dry runs and table metadata are free. A rewrite the Guard verifies
runs small queries on TEMP-table samples (BigQuery session, capped by
maximum_bytes_billed; ~30 MiB billed each, mostly the 10 MiB minimum).

Output: eval/RESULTS_bq_live_check.md and eval/results/bq_live_check_<ts>.json.

Run:
  .venv/bin/python scripts/bq_live_check.py --project $GCP_PROJECT
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "eval"))
sys.path.insert(0, str(ROOT / "scripts"))

from bq_dryrun_compare import to_bigquery  # noqa: E402
from eval_config import load_eval_customer  # noqa: E402
from run_eval import load_thelook_cases  # noqa: E402

from cost_guard.guard import decide  # noqa: E402
from cost_guard.tracing import Tracer  # noqa: E402

MIB = 1024**2
# Everything below this line in the results file is hand-written (what the
# differences mean, run history) and is kept when the table is regenerated.
NOTES_MARKER = "<!-- hand-written below: kept on rerun -->"


def _verdict(sql, customer, backend):
    try:
        v = decide(sql, customer=customer, backend=backend, tracer=Tracer())
    except Exception as e:  # noqa: BLE001 — a crash is a finding, not a stop
        return {"decision": "ERROR", "error": f"{type(e).__name__}: {str(e).splitlines()[0][:200]}"}
    return {
        "decision": v.decision,
        "reason": v.reason,
        "findings": v.findings,
        "skipped_rules": v.skipped_rules,
        "estimated_rows": v.estimated_rows,
        "estimated_bytes": v.estimated_bytes,
        "rewrite_source": v.rewrite_source,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--dataset", default="cost_guard_thelook")
    ap.add_argument("--max-bytes-billed", type=int, default=20 * 1024**3)
    ap.add_argument("--db", default=str(ROOT / "data" / "thelook.duckdb"))
    args = ap.parse_args()

    from cost_guard.backends.bigquery_backend import BigQueryWarehouse
    from cost_guard.backends.duckdb_backend import DuckDBWarehouse

    customer = load_eval_customer()
    duck = DuckDBWarehouse(args.db)
    bq = BigQueryWarehouse(args.project, args.dataset, maximum_bytes_billed=args.max_bytes_billed)

    rows = []
    for case in load_thelook_cases("eval_queries.yaml"):
        bq_sql = to_bigquery(case["sql"])
        rows.append({
            "id": case["id"],
            "duckdb": _verdict(case["sql"], customer, duck),
            "bigquery": _verdict(bq_sql, customer, bq),
            "bigquery_sql": bq_sql,
        })
        d, b = rows[-1]["duckdb"], rows[-1]["bigquery"]
        print(f'{case["id"]}: duckdb={d["decision"]:7} bigquery={b["decision"]:7} '
              + (b.get("error") or ""))

    ts = datetime.now(timezone.utc)
    out_dir = ROOT / "eval" / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"bq_live_check_{ts:%Y%m%dT%H%M%S}.json").write_text(json.dumps(rows, indent=2))
    md = ROOT / "eval" / "RESULTS_bq_live_check.md"
    notes = md.read_text().partition(NOTES_MARKER)[2] if md.exists() else ""
    md.write_text(_markdown(rows, args, ts) + "\n" + NOTES_MARKER + (notes or "\n"))
    print("wrote eval/RESULTS_bq_live_check.md")


def _markdown(rows, args, ts) -> str:
    same = sum(r["duckdb"]["decision"] == r["bigquery"]["decision"] for r in rows)
    errors = sum(r["bigquery"]["decision"] == "ERROR" for r in rows)
    pairs = Counter((r["duckdb"]["decision"], r["bigquery"]["decision"]) for r in rows)
    lines = [
        "# The Guard's check path live on BigQuery",
        "",
        f"Generated by `scripts/bq_live_check.py` on {ts:%Y-%m-%d %H:%M} UTC against "
        f"`{args.project}.{args.dataset}`. **Dry runs; a verified rewrite also runs small capped queries on samples.** "
        "Same 30 queries (tuning set) and the same frozen eval caps on both sides; "
        "BigQuery gets the query adapted by `to_bigquery()`. Not a scored eval: the "
        "labels were written for DuckDB's rows caps.",
        "",
        f"**Same verdict:** {same} of {len(rows)}. **Errors on BigQuery:** {errors}.",
        "",
        "| DuckDB → BigQuery | count |",
        "|---|---|",
        *[f"| {a} → {b} | {n} |" for (a, b), n in sorted(pairs.items())],
        "",
        "| id | DuckDB | BigQuery | BigQuery bytes | BigQuery reason / error |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        d, b = r["duckdb"], r["bigquery"]
        nbytes = f'{b["estimated_bytes"] / MIB:.3f} MiB' if b.get("estimated_bytes") else ""
        why = (b.get("error") or b.get("reason") or "").replace("|", "\\|")
        lines.append(f'| {r["id"]} | {d["decision"]} | {b["decision"]} | {nbytes} | {why[:220]} |')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
